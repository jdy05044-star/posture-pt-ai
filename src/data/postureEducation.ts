  whatWeObserve: string
  /** 왜 이 부위를 관찰하는지 (임상적 의미) */
  whyItMatters: string
  /** 자주 관찰되는 정렬 패턴 (진단명이 아니라 '관찰상 패턴' 수준의 표현) */
